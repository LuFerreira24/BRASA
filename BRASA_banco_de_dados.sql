BEGIN;

-- 1. CLIENTE
CREATE TABLE cliente (
    id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    cpf_cnpj VARCHAR(18) NOT NULL UNIQUE,
    telefone VARCHAR(20),
    email VARCHAR(150),
    endereco VARCHAR(255),
    data_cadastro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

-- 2. VEICULO
CREATE TABLE veiculo (
    id_veiculo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES cliente(id_cliente),
    placa VARCHAR(10) NOT NULL UNIQUE,
    modelo VARCHAR(100) NOT NULL,
    marca VARCHAR(100) NOT NULL,
    ano INTEGER CHECK (ano IS NULL OR ano BETWEEN 1886 AND 2100),
    cor VARCHAR(50),
    chassi VARCHAR(50) UNIQUE,
    data_cadastro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

-- 3. USUARIO
CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT UNIQUE REFERENCES cliente(id_cliente),
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_cadastro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_acesso TIMESTAMP
);

-- 4. PERFIL
CREATE TABLE perfil (
    id_perfil BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(50) NOT NULL UNIQUE,
    descricao VARCHAR(255)
);

-- 5. USUARIO_PERFIL (associativa N:N)
CREATE TABLE usuario_perfil (
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    id_perfil BIGINT NOT NULL REFERENCES perfil(id_perfil),
    PRIMARY KEY (id_usuario, id_perfil)
);

-- 6. ORDEM_SERVICO
CREATE TABLE ordem_servico (
    id_os BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES cliente(id_cliente),
    id_veiculo BIGINT NOT NULL REFERENCES veiculo(id_veiculo),
    motivo_visita TEXT NOT NULL,
    observacoes TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'ABERTA'
        CHECK (status IN ('ABERTA', 'EM_ANALISE', 'AGUARDANDO_APROVACAO',
                          'EM_EXECUCAO', 'PRONTO', 'ENTREGUE', 'CANCELADA')),
    valor_total NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (valor_total >= 0),
    data_abertura TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_previsao TIMESTAMP,
    data_finalizacao TIMESTAMP,
    CHECK (data_previsao IS NULL OR data_previsao >= data_abertura)
);

-- 7. OS_FUNCIONARIO (associativa N:N)
CREATE TABLE os_funcionario (
    id_os BIGINT NOT NULL REFERENCES ordem_servico(id_os),
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    responsabilidade VARCHAR(100),
    data_inicio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_fim TIMESTAMP,
    PRIMARY KEY (id_os, id_usuario),
    CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);

-- 8. SERVICO
CREATE TABLE servico (
    id_servico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    descricao TEXT,
    preco_atual NUMERIC(12,2) NOT NULL CHECK (preco_atual >= 0),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_cadastro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 9. PECA
CREATE TABLE peca (
    id_peca BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nome VARCHAR(150) NOT NULL,
    marca VARCHAR(100),
    preco_custo NUMERIC(12,2) CHECK (preco_custo IS NULL OR preco_custo >= 0),
    preco_venda NUMERIC(12,2) CHECK (preco_venda IS NULL OR preco_venda >= 0),
    quantidade_estoque INTEGER NOT NULL DEFAULT 0 CHECK (quantidade_estoque >= 0),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_cadastro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 10. OS_SERVICO (servicos vinculados a uma OS)
CREATE TABLE os_servico (
    id_os_servico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_os BIGINT NOT NULL REFERENCES ordem_servico(id_os),
    id_servico BIGINT NOT NULL REFERENCES servico(id_servico),
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    valor_unitario NUMERIC(12,2) NOT NULL CHECK (valor_unitario >= 0),
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    observacoes TEXT
);

-- 11. OS_PECA (pecas vinculadas a uma OS)
CREATE TABLE os_peca (
    id_os_peca BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_os BIGINT NOT NULL REFERENCES ordem_servico(id_os),
    id_peca BIGINT NOT NULL REFERENCES peca(id_peca),
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    valor_unitario NUMERIC(12,2) NOT NULL CHECK (valor_unitario >= 0),
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0)
);

-- 12. VISTORIA
CREATE TABLE vistoria (
    id_vistoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_os BIGINT NOT NULL REFERENCES ordem_servico(id_os),
    id_usuario_responsavel BIGINT NOT NULL REFERENCES usuario(id_usuario),
    quilometragem INTEGER CHECK (quilometragem IS NULL OR quilometragem >= 0),
    nivel_combustivel VARCHAR(30),
    observacoes TEXT,
    data_vistoria TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 13. ITEM_CHECKLIST
CREATE TABLE item_checklist (
    id_item BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    descricao TEXT,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

-- 14. VISTORIA_ITEM (resultado de cada item)
CREATE TABLE vistoria_item (
    id_vistoria BIGINT NOT NULL REFERENCES vistoria(id_vistoria),
    id_item BIGINT NOT NULL REFERENCES item_checklist(id_item),
    status VARCHAR(30) NOT NULL
        CHECK (status IN ('OK', 'AVARIADO', 'AUSENTE', 'NAO_VERIFICADO')),
    observacao TEXT,
    PRIMARY KEY (id_vistoria, id_item)
);

-- 15. VISTORIA_ANEXO (referencia para fotos/arquivos na nuvem)
CREATE TABLE vistoria_anexo (
    id_anexo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_vistoria BIGINT NOT NULL REFERENCES vistoria(id_vistoria),
    url_arquivo VARCHAR(500) NOT NULL,
    tipo_arquivo VARCHAR(100),
    descricao VARCHAR(255),
    data_upload TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 16. ORCAMENTO
CREATE TABLE orcamento (
    id_orcamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_os BIGINT NOT NULL REFERENCES ordem_servico(id_os),
    numero_versao INTEGER NOT NULL CHECK (numero_versao > 0),
    valor_total NUMERIC(12,2) NOT NULL CHECK (valor_total >= 0),
    status VARCHAR(30) NOT NULL DEFAULT 'PENDENTE'
        CHECK (status IN ('PENDENTE', 'APROVADO', 'RECUSADO', 'EXPIRADO', 'SUBSTITUIDO')),
    data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_envio TIMESTAMP,
    validade TIMESTAMP,
    observacoes TEXT,
    UNIQUE (id_os, numero_versao)
);

-- 17. ORCAMENTO_ITEM (cada item deve ser uma peca OU um servico)
CREATE TABLE orcamento_item (
    id_orcamento_item BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orcamento BIGINT NOT NULL REFERENCES orcamento(id_orcamento),
    tipo_item VARCHAR(20) NOT NULL CHECK (tipo_item IN ('PECA', 'SERVICO')),
    id_peca BIGINT REFERENCES peca(id_peca),
    id_servico BIGINT REFERENCES servico(id_servico),
    descricao VARCHAR(255),
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    valor_unitario NUMERIC(12,2) NOT NULL CHECK (valor_unitario >= 0),
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    CHECK (
        (tipo_item = 'PECA' AND id_peca IS NOT NULL AND id_servico IS NULL)
        OR
        (tipo_item = 'SERVICO' AND id_servico IS NOT NULL AND id_peca IS NULL)
    )
);

-- 18. APROVACAO_ORCAMENTO
CREATE TABLE aprovacao_orcamento (
    id_aprovacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orcamento BIGINT NOT NULL REFERENCES orcamento(id_orcamento),
    id_usuario_cliente BIGINT NOT NULL REFERENCES usuario(id_usuario),
    decisao VARCHAR(20) NOT NULL CHECK (decisao IN ('APROVADO', 'RECUSADO')),
    observacao TEXT,
    data_resposta TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 19. HISTORICO_OS
CREATE TABLE historico_os (
    id_historico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_os BIGINT NOT NULL REFERENCES ordem_servico(id_os),
    id_usuario BIGINT REFERENCES usuario(id_usuario),
    tipo_alteracao VARCHAR(100) NOT NULL,
    campo_alterado VARCHAR(100),
    valor_anterior TEXT,
    valor_novo TEXT,
    descricao TEXT,
    data_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 20. PAGAMENTO
CREATE TABLE pagamento (
    id_pagamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_os BIGINT NOT NULL REFERENCES ordem_servico(id_os),
    valor NUMERIC(12,2) NOT NULL CHECK (valor > 0),
    forma_pagamento VARCHAR(30) NOT NULL
        CHECK (forma_pagamento IN ('DINHEIRO', 'PIX', 'CARTAO_CREDITO',
                                   'CARTAO_DEBITO', 'BOLETO', 'TRANSFERENCIA', 'OUTRO')),
    status VARCHAR(30) NOT NULL DEFAULT 'PENDENTE'
        CHECK (status IN ('PENDENTE', 'PAGO', 'CANCELADO', 'ESTORNADO')),
    data_pagamento TIMESTAMP,
    comprovante VARCHAR(500),
    observacoes TEXT
);

-- 21. MOVIMENTACAO_ESTOQUE
CREATE TABLE movimentacao_estoque (
    id_movimentacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_peca BIGINT NOT NULL REFERENCES peca(id_peca),
    id_os BIGINT REFERENCES ordem_servico(id_os),
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    tipo VARCHAR(30) NOT NULL
        CHECK (tipo IN ('ENTRADA', 'SAIDA', 'RESERVA', 'LIBERACAO_RESERVA', 'AJUSTE', 'DEVOLUCAO')),
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    observacao TEXT,
    data_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 22. NOTIFICACAO
CREATE TABLE notificacao (
    id_notificacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_os BIGINT NOT NULL REFERENCES ordem_servico(id_os),
    id_cliente BIGINT NOT NULL REFERENCES cliente(id_cliente),
    canal VARCHAR(20) NOT NULL CHECK (canal IN ('EMAIL', 'SMS', 'WHATSAPP')),
    mensagem TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
        CHECK (status IN ('PENDENTE', 'ENVIADA', 'FALHA')),
    data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_envio TIMESTAMP
);

-- 23. LOG_OPERACAO
CREATE TABLE log_operacao (
    id_log BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT REFERENCES usuario(id_usuario),
    operacao VARCHAR(150) NOT NULL,
    entidade VARCHAR(100),
    id_registro BIGINT,
    dados_anteriores TEXT,
    dados_novos TEXT,
    ip_origem VARCHAR(45),
    data_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Indices para acelerar consultas comuns
CREATE INDEX idx_veiculo_cliente ON veiculo(id_cliente);
CREATE INDEX idx_os_cliente ON ordem_servico(id_cliente);
CREATE INDEX idx_os_veiculo ON ordem_servico(id_veiculo);
CREATE INDEX idx_os_status ON ordem_servico(status);
CREATE INDEX idx_os_data_abertura ON ordem_servico(data_abertura);
CREATE INDEX idx_os_servico_os ON os_servico(id_os);
CREATE INDEX idx_os_peca_os ON os_peca(id_os);
CREATE INDEX idx_vistoria_os ON vistoria(id_os);
CREATE INDEX idx_orcamento_os ON orcamento(id_os);
CREATE INDEX idx_pagamento_os ON pagamento(id_os);
CREATE INDEX idx_movimentacao_peca ON movimentacao_estoque(id_peca);
CREATE INDEX idx_historico_os_data ON historico_os(id_os, data_hora);
CREATE INDEX idx_notificacao_cliente ON notificacao(id_cliente);

-- Perfis iniciais previstos no documento
INSERT INTO perfil (nome, descricao) VALUES
    ('Cliente', 'Consulta suas ordens de servico e responde a orcamentos'),
    ('Atendente', 'Gerencia cadastros, ordens de servico e pagamentos'),
    ('Mecanico', 'Realiza vistorias e atualiza o andamento dos servicos'),
    ('Estoque', 'Gerencia pecas, quantidades e movimentacoes de estoque'),
    ('Administrador', 'Acesso administrativo e relatorios')
ON CONFLICT (nome) DO NOTHING;

-- Itens iniciais de checklist: podem ser alterados conforme a oficina
INSERT INTO item_checklist (nome, descricao) VALUES
    ('Pneus', 'Verificar estado dos pneus'),
    ('Faróis', 'Verificar funcionamento e estado dos farois'),
    ('Retrovisores', 'Verificar presenca e estado dos retrovisores'),
    ('Lataria', 'Registrar avarias aparentes na lataria'),
    ('Vidros', 'Verificar estado dos vidros'),
    ('Itens de seguranca', 'Verificar itens de seguranca do veiculo')
;

COMMIT;

